/**
 * What an install or a removal would do, decided before anything is written.
 *
 * Pure over injected reads, following `dns disable`: the plan is a value, and
 * `--dry-run` prints it rather than running a second implementation that can
 * drift from the real one. A test asserts the dry-run output matches the real
 * run's plan line for line.
 *
 * Every blocker is decided here too. The prompt rules in `AGENTS.md` require
 * that anything checkable up front is reported up front rather than at the
 * moment of writing.
 */

import * as path from 'path';
import { identifyBlock, insertBlock, replaceBlock } from './marker-block';
import { Ownership, RenderedFile } from './targets';
import { SKILL_TEMPLATE_VERSION } from './version';

export interface PlanDependencies {
  /** File content, or undefined when the path does not exist. */
  readText: (absolutePath: string) => string | undefined;
  exists: (absolutePath: string) => boolean;
  /** The next non-clobbering backup path for a file about to change. */
  backupPathFor: (absolutePath: string) => string;
}

export type FileAction =
  /** Nothing there yet. */
  | 'create'
  /** Ours, at an older template version. */
  | 'update'
  /** Ours, current, and the bytes already match. Nothing to do. */
  | 'unchanged'
  /** Ours and current, but the content differs — the user edited it. */
  | 'skip-modified'
  /** As above, with `--force`: keep a copy, then rewrite. */
  | 'backup-then-update'
  /** A user's file with no marker: add our span, after confirmation. */
  | 'append-block'
  /** A user's file with our span: replace what is between the markers. */
  | 'replace-block'
  /** Ours, and the current template no longer emits it. */
  | 'remove-orphan'
  /** Remove our span or our file. */
  | 'delete';

export interface PlannedFile {
  absolutePath: string;
  relativePath: string;
  ownership: Ownership;
  action: FileAction;
  backupPath?: string;
  /** Why, in words the confirmation prompt can print verbatim. */
  note?: string;
  /** The bytes to write. Absent for actions that write nothing. */
  content?: string;
}

export interface Blocker {
  absolutePath: string;
  reason: string;
}

export interface Plan {
  root: string;
  targetIds: string[];
  files: PlannedFile[];
  /**
   * When non-empty, the plan is not actionable. Blockers *replace* the plan in
   * the output rather than appearing beneath it: a blocked run has no plan to
   * describe, and "nothing to change" printed above an error reads as if there
   * were nothing to do.
   */
  blockers: Blocker[];
}

export interface PlanRequest {
  root: string;
  targetIds: string[];
  files: RenderedFile[];
  force: boolean;
}

/**
 * `relativePath` is slash-separated because that is the canonical form in the
 * target table and in every vendor's documentation. The absolute path is joined
 * with the platform separator, because it is what gets printed to a user about
 * to approve a write, and a half-and-half path reads like a bug.
 *
 * `path` here is doing string arithmetic only; this module still touches no
 * filesystem.
 */
function join(root: string, relativePath: string): string {
  return path.join(root, ...relativePath.split('/'));
}

function planOwnedFile(
  absolutePath: string,
  file: RenderedFile,
  existing: string | undefined,
  force: boolean,
  deps: PlanDependencies
): PlannedFile {
  const base = { absolutePath, relativePath: file.relativePath, ownership: file.ownership, content: file.content };

  if (existing === undefined) {
    return { ...base, action: 'create' };
  }
  if (existing === file.content) {
    // Deliberately before any backup decision: a repeated install must not
    // accumulate .bak, .bak2, .bak3. This mirrors updateComposeFile, which
    // returns early on an identical file before it copies anything.
    return { ...base, action: 'unchanged', content: undefined };
  }

  const status = identifyBlock(existing, SKILL_TEMPLATE_VERSION);
  const ours = existing.includes('runestone:generated') || status.kind !== 'absent';

  if (!ours) {
    return force
      ? { ...base, action: 'backup-then-update', backupPath: deps.backupPathFor(absolutePath), note: 'not generated by Runestone; forced' }
      : { ...base, action: 'skip-modified', content: undefined, note: 'exists and was not generated by Runestone' };
  }

  const stale = status.kind === 'stale' || !existing.includes(`skill-template=${SKILL_TEMPLATE_VERSION}`);
  if (stale) {
    return { ...base, action: 'update' };
  }

  // Ours, current version, different bytes: the user edited it, or `.env`
  // changed since it was written. The two are observationally identical and
  // both are handled the same way — keep what is there unless forced.
  return force
    ? { ...base, action: 'backup-then-update', backupPath: deps.backupPathFor(absolutePath), note: 'modified since install; forced' }
    : { ...base, action: 'skip-modified', content: undefined, note: 'modified since install, or Runestone settings changed' };
}

function planBlockFile(
  absolutePath: string,
  file: RenderedFile,
  existing: string | undefined,
  deps: PlanDependencies
): PlannedFile | Blocker {
  const base = { absolutePath, relativePath: file.relativePath, ownership: file.ownership };

  if (existing === undefined) {
    return { ...base, action: 'create', content: insertBlock('', file.content, SKILL_TEMPLATE_VERSION) };
  }

  const status = identifyBlock(existing, SKILL_TEMPLATE_VERSION);

  if (status.kind === 'conflict') {
    return {
      absolutePath,
      reason:
        `contains ${status.offsets.length} Runestone begin markers, at offsets ${status.offsets.join(' and ')}. ` +
        'Runestone will not guess which span is its own. Remove the extra marker pair by hand, or delete both and reinstall.'
    };
  }
  if (status.kind === 'unterminated') {
    return {
      absolutePath,
      reason:
        `has a Runestone begin marker at offset ${status.offset} with no matching end marker, so the extent of ` +
        'the span is unknown. Close it or delete it by hand, then reinstall.'
    };
  }
  if (status.kind === 'absent') {
    return {
      ...base,
      action: 'append-block',
      content: insertBlock(existing, file.content, SKILL_TEMPLATE_VERSION),
      backupPath: deps.backupPathFor(absolutePath),
      note: 'appending a Runestone section; the rest of the file is untouched'
    };
  }

  const next = replaceBlock(existing, status.span, file.content, SKILL_TEMPLATE_VERSION);
  if (next === existing) {
    return { ...base, action: 'unchanged' };
  }

  return {
    ...base,
    action: 'replace-block',
    content: next,
    backupPath: deps.backupPathFor(absolutePath),
    note: status.kind === 'stale' ? 'updating an older Runestone section' : 'refreshing the Runestone section'
  };
}

function isBlocker(value: PlannedFile | Blocker): value is Blocker {
  return (value as Blocker).reason !== undefined && (value as PlannedFile).action === undefined;
}

export function planInstall(request: PlanRequest, deps: PlanDependencies): Plan {
  const files: PlannedFile[] = [];
  const blockers: Blocker[] = [];

  for (const file of request.files) {
    const absolutePath = join(request.root, file.relativePath);
    const existing = deps.readText(absolutePath);

    if (file.ownership === 'block') {
      const outcome = planBlockFile(absolutePath, file, existing, deps);
      if (isBlocker(outcome)) {
        blockers.push(outcome);
      } else {
        files.push(outcome);
      }
      continue;
    }

    files.push(planOwnedFile(absolutePath, file, existing, request.force, deps));
  }

  return { root: request.root, targetIds: request.targetIds, files, blockers };
}

/**
 * The inverse. Owned files carrying our marker are deleted; a marked span is
 * spliced out and the rest of the file left alone.
 *
 * A file that does not carry our marker is never deleted without `--force`,
 * and a whole-file backup is never restored — the same prohibition the DNS
 * specification places on `daemon.json`, for the same reason: restoring would
 * discard unrelated edits made since.
 */
export function planRemove(request: PlanRequest, deps: PlanDependencies): Plan {
  const files: PlannedFile[] = [];
  const blockers: Blocker[] = [];

  for (const file of request.files) {
    const absolutePath = join(request.root, file.relativePath);
    const existing = deps.readText(absolutePath);
    const base = { absolutePath, relativePath: file.relativePath, ownership: file.ownership };

    if (existing === undefined) {
      continue;
    }

    if (file.ownership === 'block') {
      const status = identifyBlock(existing, SKILL_TEMPLATE_VERSION);
      if (status.kind === 'conflict' || status.kind === 'unterminated') {
        blockers.push({
          absolutePath,
          reason:
            'the Runestone markers in this file are not a single well-formed pair, so removing them automatically ' +
            'could take the wrong bytes. Remove the section by hand.'
        });
        continue;
      }
      if (status.kind === 'absent') {
        continue;
      }

      files.push({ ...base, action: 'delete', note: 'removing only the Runestone section' });
      continue;
    }

    const ours = existing.includes('runestone:generated') || existing.includes('runestone-skill-template');
    if (!ours && !request.force) {
      files.push({ ...base, action: 'skip-modified', note: 'not generated by Runestone; left in place' });
      continue;
    }

    files.push({ ...base, action: 'delete' });
  }

  return { root: request.root, targetIds: request.targetIds, files, blockers };
}

/** True when the plan would write nothing. */
export function isNoOp(plan: Plan): boolean {
  return plan.files.every((file) => file.action === 'unchanged' || file.action === 'skip-modified');
}
